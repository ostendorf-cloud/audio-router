# Usage: render-cask.sh <version> <sha256> <output file>
#
# Writes the Homebrew cask for the release zip audio-router-<version>-arm64.zip
# that app-release.yaml attaches to the GitHub release. The cask is generated,
# never edited by hand in the tap: publish-homebrew-cask.sh renders it from the
# hash of the published zip and pushes it to ostendorf-cloud/homebrew-tap.
#
# The output depends on the two arguments only, so the same version and hash
# always give the same file and a rerun of the release leaves the tap alone.
#
# Facts behind the stanzas:
#   depends_on macos: Info.plist sets LSMinimumSystemVersion 14.2. Homebrew
#     covers major releases only, so the floor is :sonoma (macOS 14). A Mac on
#     14.0 or 14.1 passes this check and the app then refuses to start.
#   depends_on arch: the zip holds an arm64 build only, see task bundle:verify.
#   zap: RouteStore keeps the routes in ~/Library/Application Support/audio-router.
#     The preferences file is named after CFBundleIdentifier in
#     Resources/Info.plist.template.
#   No postflight: the quarantine attribute stays, and Gatekeeper keeps
#     warning until the app is signed and notarized.
set -euo pipefail

if [ "$#" -ne 3 ]; then
  echo "usage: $0 <version> <sha256> <output file>" >&2
  exit 2
fi

version="$1"
sha256="$2"
out="$3"

# A plain MAJOR.MINOR.PATCH only: a pre-release never reaches the tap.
num='(0|[1-9][0-9]*)'
if ! [[ ${version} =~ ^${num}\.${num}\.${num}$ ]]; then
  echo "render-cask: version '${version}' is not MAJOR.MINOR.PATCH" >&2
  exit 2
fi
if ! [[ ${sha256} =~ ^[0-9a-f]{64}$ ]]; then
  echo "render-cask: sha256 '${sha256}' is not 64 lower case hex digits" >&2
  exit 2
fi

# The Ruby interpolation #{version} is meant literally, so the lines with it
# are in single quotes.
# shellcheck disable=SC2016
{
  echo '# Generated by scripts/render-cask.sh in ostendorf-cloud/audio-router. Do not edit.'
  echo 'cask "audio-router" do'
  echo "  version \"${version}\""
  echo "  sha256 \"${sha256}\""
  echo ''
  echo '  url "https://github.com/ostendorf-cloud/audio-router/releases/download/v#{version}/audio-router-#{version}-arm64.zip"'
  echo '  name "audio-router"'
  echo '  desc "Routes the audio of single apps to channel pairs of any output device"'
  echo '  homepage "https://github.com/ostendorf-cloud/audio-router"'
  echo ''
  echo '  livecheck do'
  echo '    url :url'
  echo '    strategy :github_latest'
  echo '  end'
  echo ''
  echo '  depends_on arch: :arm64'
  echo '  depends_on macos: :sonoma'
  echo ''
  echo '  app "audio-router.app"'
  echo ''
  echo '  zap trash: ['
  echo '    "~/Library/Application Support/audio-router",'
  echo '    "~/Library/Preferences/cloud.ostendorf.audio-router.plist",'
  echo '  ]'
  echo 'end'
} >"${out}"
