# Tests for render-cask.sh: the cask for a version and a hash, byte for byte,
# the same file on a second render, and the refusal of a bad version or hash.
# Runs in an empty temporary directory and calls no network and no brew.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
render="${script_dir}/render-cask.sh"
# An explicit template, because macOS mktemp ignores TMPDIR without one.
work="$(mktemp -d "${TMPDIR:-/tmp}/render-cask-test.XXXXXXXX")"
finished=no
trap 'rm -rf "${work}"; if [ "${finished}" != yes ]; then if [ "${failures:-0}" -eq 0 ]; then echo "test script stopped before its last line" >&2; fi; exit 1; fi' EXIT
cd "${work}"

failures=0
fail() {
  echo "FAIL $1"
  failures=$((failures + 1))
}

hash="0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"

# The whole cask, so every stanza and its order is pinned. The #{version} is
# Ruby interpolation and stays literal.
cat <<'EOF' >want.rb
# Generated by scripts/render-cask.sh in ostendorf-cloud/audio-router. Do not edit.
cask "audio-router" do
  version "1.2.3"
  sha256 "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"

  url "https://github.com/ostendorf-cloud/audio-router/releases/download/v#{version}/audio-router-#{version}-arm64.zip"
  name "audio-router"
  desc "Routes the audio of single apps to channel pairs of any output device"
  homepage "https://github.com/ostendorf-cloud/audio-router"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on macos: :sonoma

  app "audio-router.app"

  zap trash: [
    "~/Library/Application Support/audio-router",
    "~/Library/Preferences/cloud.ostendorf.audio-router.plist",
  ]
end
EOF

if "${render}" 1.2.3 "${hash}" first.rb && "${render}" 1.2.3 "${hash}" second.rb; then
  if cmp -s first.rb second.rb; then
    echo "PASS two renders of the same input are identical"
  else
    fail "two renders of the same input differ"
  fi
  if cmp -s first.rb want.rb; then
    echo "PASS the cask is the expected file"
  else
    fail "the cask differs from the expected file: $(diff want.rb first.rb || true)"
  fi
else
  fail "render failed on a valid version and hash"
fi

# The bundle id in the zap path must be the one the app is built with.
bundle_id="$(sed -n -E '/<key>CFBundleIdentifier<\/key>/{n;s/.*<string>(.*)<\/string>.*/\1/p;}' "${script_dir}/../Resources/Info.plist.template")"
# The tilde is part of the cask text, not a path of this machine.
# shellcheck disable=SC2088
if [ -n "${bundle_id}" ] && grep -qF "~/Library/Preferences/${bundle_id}.plist" first.rb; then
  echo "PASS the preferences path carries the bundle id ${bundle_id}"
else
  fail "the preferences path does not carry the bundle id '${bundle_id}' of Resources/Info.plist.template"
fi

# A different version or hash gives a different cask.
"${render}" 1.2.4 "${hash}" other.rb
if grep -qxF '  version "1.2.4"' other.rb && ! cmp -s first.rb other.rb; then
  echo "PASS another version renders another cask"
else
  fail "another version did not change the cask"
fi

# refuse name args...: each must exit 2 and write no file.
# A file the script did write would carry the name refused.rb.
refuse() {
  local name="$1" status=0
  shift
  rm -f refused.rb
  "${render}" "$@" >/dev/null 2>&1 || status=$?
  if [ "${status}" -ne 2 ]; then
    fail "${name}: exit status = ${status}, want 2"
  elif [ -e refused.rb ]; then
    fail "${name}: a file was written"
  else
    echo "PASS ${name}"
  fi
}

refuse "a pre-release version is refused" 1.2.3-rc.1 "${hash}" refused.rb
refuse "a version with a v is refused" v1.2.3 "${hash}" refused.rb
refuse "a version with a leading zero is refused" 01.2.3 "${hash}" refused.rb
refuse "a short hash is refused" 1.2.3 "${hash%?}" refused.rb
refuse "an upper case hash is refused" 1.2.3 "$(tr 'a-f' 'A-F' <<<"${hash}")" refused.rb
refuse "a missing argument is refused" 1.2.3 "${hash}"

if [ "${failures}" -ne 0 ]; then
  finished=yes
  echo "${failures} test(s) failed"
  exit 1
fi

finished=yes
echo "all tests passed"
